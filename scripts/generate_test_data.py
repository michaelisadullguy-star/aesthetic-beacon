"""Generate a simulated study for trying the workflow without a headset.

The data is written in the same formats and folders as real recordings:
headset hex logs, WAV audio, an article, a keystroke log and artwork images.
Unlike random numbers, it contains relationships the pipeline can recover —
see ``src/simulator.py`` — and the ground truth is saved as ``demo_truth.json``.

Usage:
    python scripts/generate_test_data.py --output data/
    python scripts/generate_test_data.py --output demo_data/ --seed 3
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.simulator import generate_demo_dataset  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=Path("data"), help="Directory to write the study to")
    parser.add_argument("--seed", type=int, default=0, help="Seed of the simulation")
    parser.add_argument("--sample-rate", type=int, default=640, help="Sampling rate of the simulated headset")
    parser.add_argument("--listeners", type=int, default=4)
    parser.add_argument("--readers", type=int, default=4)
    parser.add_argument("--viewers", type=int, default=4)
    parser.add_argument("--artworks", type=int, default=6)
    parser.add_argument("--passages", type=int, default=12)
    args = parser.parse_args()

    if (args.output / "demo_truth.json").exists() or not any(args.output.glob("step*/*/*")):
        pass
    else:
        print(f"{args.output} already contains data that was not generated by this script; refusing to mix.")
        return 1

    truth = generate_demo_dataset(
        args.output,
        seed=args.seed,
        sample_rate=args.sample_rate,
        listeners=args.listeners,
        readers=args.readers,
        viewers=args.viewers,
        artworks=args.artworks,
        passages=args.passages,
    )
    print(f"Simulated study written to {args.output}")
    print(f"  excellent passages (ground truth): {[i + 1 for i in truth['excellent_passages']]}")
    print("Next: python src/workflow_orchestrator.py --all")
    return 0


if __name__ == "__main__":
    sys.exit(main())
